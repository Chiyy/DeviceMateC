#!/bin/bash
# ============================================================
# DeviceMate USB 存储设备诊断脚本 (macOS)
#
# 用途: 当 DeviceMate 无法检测到 USB 存储设备时, 运行此脚本
#       收集所有相关系统命令的原始输出, 便于排查问题。
#
# 用法:
#   chmod +x debug_usb.sh
#   ./debug_usb.sh           # 输出到终端
#   ./debug_usb.sh > debug.txt 2>&1  # 保存到文件后发送给开发者
# ============================================================

set -e

echo "============================================================"
echo " DeviceMate USB 存储设备诊断报告"
echo " 日期: $(date '+%Y-%m-%d %H:%M:%S')"
echo " 主机: $(hostname)"
echo " 系统: $(sw_vers -productName) $(sw_vers -productVersion)"
echo " 架构: $(uname -m)"
echo "============================================================"
echo ""

# ------------------------------------------------------------
# 1. diskutil list external physical
#    列出外部物理磁盘 (USB 存储设备的主要来源)
# ------------------------------------------------------------
echo "============================================================"
echo " [1] diskutil list external physical"
echo "    (外部物理磁盘列表, USB 存储设备的主要来源)"
echo "============================================================"
diskutil list external physical 2>&1 || echo "(命令执行失败)"
echo ""

# ------------------------------------------------------------
# 2. diskutil list external
#    列出所有外部磁盘 (含虚拟)
# ------------------------------------------------------------
echo "============================================================"
echo " [2] diskutil list external"
echo "    (所有外部磁盘, 含虚拟磁盘映像)"
echo "============================================================"
diskutil list external 2>&1 || echo "(命令执行失败)"
echo ""

# ------------------------------------------------------------
# 3. diskutil list
#    列出所有磁盘 (用于对比, 排除内置磁盘)
# ------------------------------------------------------------
echo "============================================================"
echo " [3] diskutil list"
echo "    (所有磁盘, 用于对比内置 vs 外部)"
echo "============================================================
diskutil list 2>&1 || echo "(命令执行失败)"
echo ""

# ------------------------------------------------------------
# 4. ioreg -c IOBlockStorageDevice
#    IORegistry 中的块存储设备 (含序列号/型号/BSD Name)
# ------------------------------------------------------------
echo "============================================================"
echo " [4] ioreg -r -d 5 -w 0 -c IOBlockStorageDevice"
echo "    (IORegistry 块存储设备, 含序列号/型号/BSD Name)"
echo "============================================================"
ioreg -r -d 5 -w 0 -c IOBlockStorageDevice 2>&1 || echo "(命令执行失败)"
echo ""

# ------------------------------------------------------------
# 5. ioreg -c IOUSBHostDevice
#    IORegistry 中的 USB 主机设备 (USB 设备树)
# ------------------------------------------------------------
echo "============================================================"
echo " [5] ioreg -r -d 5 -w 0 -l -c IOUSBHostDevice"
echo "    (IORegistry USB 设备树, 查看子节点的 BSD Name)"
echo "============================================================"
ioreg -r -d 5 -w 0 -l -c IOUSBHostDevice 2>&1 || echo "(命令执行失败)"
echo ""

# ------------------------------------------------------------
# 6. system_profiler SPUSBDataType
#    系统报告: USB 设备树 (最全面的 USB 设备信息)
# ------------------------------------------------------------
echo "============================================================"
echo " [6] system_profiler SPUSBDataType"
echo "    (系统报告 USB 设备树, 最全面的 USB 信息)"
echo "============================================================"
system_profiler SPUSBDataType 2>&1 || echo "(命令执行失败)"
echo ""

# ------------------------------------------------------------
# 7. 挂载的卷 (确认 USB 设备是否已挂载)
# ------------------------------------------------------------
echo "============================================================"
echo " [7] mount | grep /dev/disk"
echo "    (已挂载的磁盘卷, 确认 USB 设备是否被系统识别)"
echo "============================================================"
mount 2>/dev/null | grep '/dev/disk' || echo "(无磁盘挂载)"
echo ""

# ------------------------------------------------------------
# 8. /dev/disk 设备文件
# ------------------------------------------------------------
echo "============================================================"
echo " [8] ls -la /dev/disk*"
echo "    (磁盘设备文件列表)"
echo "============================================================"
ls -la /dev/disk* 2>&1 || echo "(无磁盘设备文件)"
echo ""

# ------------------------------------------------------------
# 总结
# ------------------------------------------------------------
echo "============================================================"
echo " 诊断完成"
echo ""
echo " 如果 DeviceMate 仍无法检测到 USB 存储设备:"
echo "   1. 确认 USB 设备已插入并被 macOS 识别 (检查 [3] 和 [7])"
echo "   2. 确认设备出现在 [1] diskutil 外部物理磁盘列表中"
echo "   3. 确认设备有 BSD Name 属性 (检查 [4] 或 [6] 输出)"
echo "   4. 确认设备有 removable/ejectable = YES (检查 [4])"
echo "   5. 运行 DeviceMate --debug-usb 查看解析日志"
echo "   6. 将此输出保存并发送给开发者: ./debug_usb.sh > debug.txt 2>&1"
echo "============================================================"
